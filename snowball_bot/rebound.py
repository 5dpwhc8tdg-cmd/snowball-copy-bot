"""Сколько отскока остаётся при позднем входе — измерено, а не на глаз.

Измерение (`research_lag.py`, 40 бумаг из портфеля, 21 день, 53 события
«падение ≥4% за 60 минут», вход по закрытию свечи в момент t+лаг):

  лаг входа │ осталось взять (макс. за 2 ч) │ к концу дня │ уже упущено │ риск
  ──────────┼───────────────────────────────┼─────────────┼────────────┼──────────────
   0 мин    │ медиана +2,81%, в плюсе 94%   │ +3,12% (81%)│ +0,65%     │ до −0,65%
  10 мин    │ +1,92%, 88%                   │ +2,11% (68%)│ +1,68%     │ —
  20 мин    │ +1,82%, 80%                   │ +2,01% (70%)│ +2,40%     │ —
  30 мин    │ +1,47%, 78%                   │ +1,56% (66%)│ +3,13%     │ до −3,04%
  45 мин    │ +1,69%, 82%                   │ +1,56% (66%)│ +2,43%     │ —
  60 мин    │ +1,42%, 76%                   │ +1,65% (69%)│ +2,71%     │ до −2,64%
  90 мин    │ +1,59%, 76%                   │ +1,65% (68%)│ +2,50%     │ —
 120 мин    │ +1,38%, 88%                   │ +1,56% (74%)│ +2,13%     │ —

Выводы, на которых стоит логика:
  * поздний вход НЕ обнуляет сделку: даже через час остаётся ~+1,4% медианно
    и 76% случаев в плюсе — это всё ещё положительное ожидание;
  * но «съедено» уже 2,5–3%, а дно наступает в среднем через 50 мин после
    сигнала (p25 10 мин, p75 130 мин) — поэтому вход с опозданием часто
    попадает ДО дна: медианная просадка после входа −3%, это норма, не повод паниковать;
  * чем глубже было падение, тем больше остаётся: 4–6% → +0,9%, 6–9% → +2,9%;
  * после 2 часов отскок уже не «отскок», а обычная позиция — ждать его бессмысленно,
    зато купон и возврат к номиналу никто не отменял.

Поэтому вердикт больше не ставит «ПОЗДНО» автоматически: он считает ожидаемый
остаток и риск, и предлагает размер позиции под это.
"""
from __future__ import annotations

# Замеры на 29 днях, 262 события: держать дольше нельзя — закрытие следующего
# дня даёт медиану −1,79%, через 2 дня −2,45% (BACKTEST.md).
DAY1_MEDIAN = -1.79
DAY2_MEDIAN = -2.45

# (лаг в минутах) -> (медиана остатка в %, доля плюсов в %, медианная просадка после входа в %)
LAG_TABLE = {
    0: (2.81, 94, -0.65),
    10: (1.92, 88, -1.20),
    20: (1.82, 80, -2.10),
    30: (1.47, 78, -3.04),
    45: (1.69, 82, -2.80),
    60: (1.42, 76, -2.64),
    90: (1.59, 76, -2.50),
    120: (1.38, 88, -2.30),
}
# поправка на глубину падения (4-6% → 0,93; 6-9% → 2,92 при лаге 30 мин)
DEPTH_FACTOR = ((6.0, 0.65), (9.0, 1.9), (999.0, 2.4))
HORIZON_NOTE = "горизонт 2 часа; к закрытию медиана −0,95%, через 1 день −1,79%"


def _bucket(lag: int) -> tuple[int, tuple[float, float, float]]:
    keys = sorted(LAG_TABLE)
    if lag <= keys[0]:
        return keys[0], LAG_TABLE[keys[0]]
    if lag >= keys[-1]:
        return keys[-1], LAG_TABLE[keys[-1]]
    lo = max(k for k in keys if k <= lag)
    hi = min(k for k in keys if k >= lag)
    if lo == hi:
        return lo, LAG_TABLE[lo]
    w = (lag - lo) / (hi - lo)
    a, b = LAG_TABLE[lo], LAG_TABLE[hi]
    return lo, tuple(a[i] + (b[i] - a[i]) * w for i in range(3))


def _depth_factor(drop_pct: float) -> float:
    for limit, factor in DEPTH_FACTOR:
        if drop_pct < limit:
            return factor
    return 1.0


def estimate(lag_min: int | None, drop_pct: float) -> dict:
    """Ожидаемый остаток отскока и риск просадки для входа с таким опозданием."""
    lag = 0 if lag_min is None else max(0, int(lag_min))
    _, (med, win, dd) = _bucket(lag)
    factor = _depth_factor(drop_pct or 4.0)
    # растягивать медиану через множитель по глубине честно только в первые
    # два часа; позже это уже не «отскок», поэтому берём базовую медиану
    med_adj = med * factor if lag <= 120 else med
    return {
        "lag": lag,
        "expect_pct": round(med_adj, 2),
        "win_share": round(win),
        "drawdown_pct": round(dd, 1),
        "stale": lag > 180,
        "useful": med_adj >= 0.8 and win >= 70,
    }


def size_factor(lag_min: int | None, drop_pct: float) -> float:
    """Какую долю обычного размера брать: поздний вход — меньшая позиция."""
    est = estimate(lag_min, drop_pct)
    if est["stale"]:
        return 0.5
    if est["expect_pct"] >= 1.5 and est["win_share"] >= 80:
        return 1.0
    if est["expect_pct"] >= 1.0:
        return 0.75
    return 0.5


def explain(lag_min: int | None, drop_pct: float) -> str:
    """Строка для карточки: «что ещё можно взять и каким размером»."""
    est = estimate(lag_min, drop_pct)
    lag = est["lag"]
    if lag <= 5:
        return (f"вход почти в моменте: медиана ещё +{est['expect_pct']:.1f}%, "
                f"в плюсе {est['win_share']}% — полный размер")
    if est["stale"]:
        # Проверено на 29 днях (BACKTEST.md): закрытие через 1 день даёт медиану
        # −1,79%, через 2 дня −2,45%. Поэтому «подождать до завтра» мы больше
        # не советуем — честнее сказать, что вход пропущен.
        return (f"прошло {lag} мин — отскок уже не поймать: по замерам через 1 день "
                f"медиана {DAY1_MEDIAN:+.1f}%, через 2 дня {DAY2_MEDIAN:+.1f}%. "
                f"Пропускать, а не «ждать до завтра»")
    note = (f"прошло {lag} мин: медиана ещё +{est['expect_pct']:.1f}% "
            f"(в плюсе {est['win_share']}%), размер {int(size_factor(lag, drop_pct) * 100)}%")
    if est["drawdown_pct"] <= -2:
        note += f"; до дна может просесть до {est['drawdown_pct']:.1f}% — ставьте лимит"
    return note
